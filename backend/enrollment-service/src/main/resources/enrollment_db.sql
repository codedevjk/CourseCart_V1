-- =========================================================================
-- ENROLLMENT SERVICE DATABASE
-- No cross-DB foreign keys. Application-level validation ensures integrity.
-- =========================================================================
CREATE DATABASE IF NOT EXISTS coursecart_enrollment_db;
USE coursecart_enrollment_db;

CREATE TABLE enrollments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    enrolled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_enrollments_user_course (user_id, course_id)
) ENGINE=InnoDB;

CREATE TABLE lesson_progress (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    enrollment_id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP NULL,
    FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    UNIQUE KEY uk_lesson_progress_enrollment_lesson (enrollment_id, lesson_id)
) ENGINE=InnoDB;

CREATE INDEX idx_enrollments_user_id ON enrollments(user_id);

